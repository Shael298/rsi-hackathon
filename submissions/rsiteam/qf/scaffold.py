def _csv_block(name: str, cols: list[str]) -> str:
    return f'    results[{name!r}] = pd.DataFrame(columns={cols!r})  # TODO: rows with exactly these columns\n'


def _json_block(name: str, keys: dict[str, str]) -> str:
    items = ", ".join(f"{k!r}: {PLACEHOLDER.get(str(t).lower(), 'None')}" for k, t in keys.items())
    return f'    results[{name!r}] = {{{items}}}  # TODO: real values, types: {keys!r}\n'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("--solve", default="/app/solve.py")
    ap.add_argument("--run", action="store_true", help="run the generated solve.py once (creates placeholder outputs)")
    a = ap.parse_args()
    with open(a.spec, encoding="utf-8") as fh:
        spec = json.load(fh)
    output_dir = spec.get("output_dir") or "/app/output"
    csv_spec = {k: list(v) for k, v in (spec.get("csv") or {}).items()}
    json_spec = {k: dict(v) for k, v in (spec.get("json") or {}).items()}
    if not csv_spec and not json_spec:
        print("spec has no csv/json outputs - add at least one", file=sys.stderr)
        return 2
    code = TEMPLATE.format(
        output_dir=output_dir, csv_spec=csv_spec, json_spec=json_spec,
        csv_blocks="".join(_csv_block(n, c) for n, c in csv_spec.items()),
        json_blocks="".join(_json_block(n, k) for n, k in json_spec.items()),
    )
    if os.path.exists(a.solve):
        print(f"{a.solve} exists; not overwriting. Delete it or pass --solve other.py", file=sys.stderr)
        return 3
    os.makedirs(os.path.dirname(os.path.abspath(a.solve)), exist_ok=True)
    with open(a.solve, "w", encoding="utf-8") as fh:
        fh.write(code)
    print(f"wrote {a.solve}: {len(csv_spec)} csv + {len(json_spec)} json outputs -> {output_dir}")
    if a.run:
        r = subprocess.run([sys.executable, a.solve], capture_output=True, text=True)
        print(r.stdout[-2000:])
        if r.returncode != 0:
            print(r.stderr[-2000:], file=sys.stderr)
            return r.returncode
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
