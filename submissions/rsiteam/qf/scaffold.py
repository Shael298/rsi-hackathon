def _cast(value, typ):
    if value is None:
        return None
    if typ == "int":
        return int(value)
    if typ == "float":
        v = float(value)
        return None if (v != v or v in (float("inf"), float("-inf"))) else v
    if typ == "bool":
        return bool(value)
    if typ in ("str", "string"):
        return str(value)
    if q is not None:
        return q.to_jsonable(value)
    return value


def write_outputs(results):
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for name, cols in CSV_SPEC.items():
        df = results.get(name)
        if not isinstance(df, pd.DataFrame):
            df = pd.DataFrame(df or [], columns=cols)
        df = df.reindex(columns=cols)
        df.to_csv(os.path.join(OUTPUT_DIR, name), index=False)
        print(f"wrote {{name}}: {{len(df)}} rows, columns={{list(df.columns)}}")
    for name, keys in JSON_SPEC.items():
        obj = results.get(name) or {{}}
        out = {{k: _cast(obj.get(k), t) for k, t in keys.items()}}
        with open(os.path.join(OUTPUT_DIR, name), "w", encoding="utf-8") as fh:
            json.dump(out, fh, indent=2)
        print(f"wrote {{name}}: keys={{list(out)}}")


def main():
    data = load_inputs()
    results = compute(data)
    write_outputs(results)


if __name__ == "__main__":
    main()
