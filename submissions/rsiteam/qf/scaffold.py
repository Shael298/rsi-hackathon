#!/usr/bin/env python3
"""scaffold.py - turn a tiny spec into a runnable solve.py that already writes every output file.

    python /harbor/skills/stbench-skill/scaffold.py /app/spec.json [--solve /app/solve.py] [--run]

spec.json (write it in ONE short tool call; strings only):
{
  "output_dir": "/app/output",
  "csv": {"lead_lag_results.csv": ["pair", "lag", "corr"], "summary_table.csv": ["metric", "value"]},
  "json": {"results.json": {"n_obs": "int", "start_date": "str", "best_lag": "int", "same_sign": "bool",
                            "top_pairs": "list", "params": "object"}}
}

What you get:
  - /app/solve.py with load_inputs(), compute(), write_outputs() and main(); compute() returns a
    dict of placeholders shaped exactly like the spec (right file names, columns, keys, types).
  - with --run: solve.py is executed once so every output file exists immediately.
Then replace the placeholders in compute() one function at a time (keep each edit under ~80 lines).
Only the standard library is used here; solve.py itself uses pandas/numpy (present in the task image).
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

PLACEHOLDER = {
    "int": "0", "float": "0.0", "bool": "False", "str": '""', "string": '""',
    "list": "[]", "object": "{}", "dict": "{}", "null": "None", "none": "None",
}

